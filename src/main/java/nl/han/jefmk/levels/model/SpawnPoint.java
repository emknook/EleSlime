package nl.han.jefmk.levels.model;

public class SpawnPoint {
    private int gridX;
    private int gridY;

    public SpawnPoint() {
    }

    public SpawnPoint(int gridX, int gridY) {
        this.gridX = gridX;
        this.gridY = gridY;
    }

    public int getGridX() {
        return gridX;
    }

    public void setGridX(int gridX) {
        this.gridX = gridX;
    }

    public int getGridY() {
        return gridY;
    }

    public void setGridY(int gridY) {
        this.gridY = gridY;
    }
}
